//! User-created theme persistence (`themes.json` in the app data dir),
//! mirroring `crate::settings`'s load/save shape. `themes.json` stores only
//! user-created themes; the built-in palettes are synthesized by
//! [`built_in_themes`] and never written to disk, so they can't drift out
//! of sync with themselves and can't be deleted or overwritten by id
//! collision.

