fn is_built_in_id(id: &str) -> bool {
    BUILT_IN_THEME_IDS.contains(&id)
}

fn themes_file_path(app_data_dir: &Path) -> PathBuf {
    app_data_dir.join(THEMES_FILENAME)
}

/// User-created themes only (never includes a built-in). Missing file
/// (first run, or an app data dir that predates this feature) is not an
/// error - just an empty library, matching `settings::load`'s
/// create-on-first-access spirit without needing to eagerly write a file
/// for the common case of "no custom themes yet."
fn load_saved(app_data_dir: &Path) -> AppResult<Vec<Theme>> {
    let path = themes_file_path(app_data_dir);
    if !path.exists() {
        return Ok(Vec::new());
    }
    let contents = fs::read_to_string(&path)?;
    let themes: Vec<Theme> = serde_json::from_str(&contents)?;
    Ok(themes)
}

fn save_all(app_data_dir: &Path, themes: &[Theme]) -> AppResult<()> {
    fs::create_dir_all(app_data_dir)?;
    let contents = serde_json::to_string_pretty(themes)?;
    fs::write(themes_file_path(app_data_dir), contents)?;
    Ok(())
}

/// Both built-in palettes, prepended, followed by every saved custom theme.
pub fn list(app_data_dir: &Path) -> AppResult<Vec<Theme>> {
    let mut all = built_in_themes();
    all.extend(load_saved(app_data_dir)?);
    Ok(all)
}

/// Built-in or a saved theme by id - used by export, which needs a
/// `ThemeColors` regardless of which kind of theme was picked.
pub fn get(app_data_dir: &Path, id: &str) -> AppResult<Theme> {
    if let Some(built_in) = built_in_themes().into_iter().find(|t| t.id == id) {
        return Ok(built_in);
    }
    load_saved(app_data_dir)?
        .into_iter()
        .find(|t| t.id == id)
        .ok_or(AppError::ThemeNotFound)
}

/// Creates a new theme (`input.id: None`) or updates an existing one in
/// place (`input.id: Some(id)`, matched by id - if no saved theme has that
/// id, it's added rather than erroring, so an id round-tripped from a
/// previous `theme_save` response always works). Rejects touching a
/// built-in id - the UI never exposes editing one (see `Theme.built_in`),
/// this is defense-in-depth only.
pub fn upsert(app_data_dir: &Path, input: ThemeInput) -> AppResult<Theme> {
    if input.id.as_deref().is_some_and(is_built_in_id) {
        return Err(AppError::Internal(
            "cannot modify a built-in theme".to_string(),
        ));
    }

    let mut saved = load_saved(app_data_dir)?;
    let theme = Theme {
        id: input.id.unwrap_or_else(new_id),
        name: input.name,
        colors: input.colors,
        built_in: false,
    };

    if let Some(existing) = saved.iter_mut().find(|t| t.id == theme.id) {
        *existing = theme.clone();
    } else {
        saved.push(theme.clone());
    }
    save_all(app_data_dir, &saved)?;
    Ok(theme)
}

/// Errors [`AppError::ThemeNotFound`] if `id` isn't a saved theme, or
/// rejects a built-in id outright (same defense-in-depth as `upsert`).
/// Does not touch `settings.toml` - if the deleted theme was active, that's
/// the caller's responsibility (`commands::theme::theme_delete`), since
/// this module has no reason to know about settings.
pub fn delete(app_data_dir: &Path, id: &str) -> AppResult<()> {
    if is_built_in_id(id) {
        return Err(AppError::Internal(
            "cannot delete a built-in theme".to_string(),
        ));
    }

    let mut saved = load_saved(app_data_dir)?;
    let before = saved.len();
    saved.retain(|t| t.id != id);
    if saved.len() == before {
        return Err(AppError::ThemeNotFound);
    }
    save_all(app_data_dir, &saved)
}

/// 16 random bytes, hex-encoded - not a `uuid` crate dependency, since
/// `rand`/`data-encoding` are already dependencies (see `crypto/mod.rs` for
/// the same `thread_rng().fill_bytes()` pattern). Timestamp-based ids were
/// considered and rejected: Windows' ~15.6ms default timer resolution makes
/// collisions plausible across rapid create/duplicate/import flows.
fn new_id() -> String {
    let mut bytes = [0u8; 16];
    rand::thread_rng().fill_bytes(&mut bytes);
    data_encoding::HEXLOWER.encode(&bytes)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_colors() -> ThemeColors {
        rose_default_colors()
    }

    /// A fresh, uniquely-named directory under the OS temp dir - avoids
    /// adding a `tempfile` dev-dependency just for these tests, matching
    /// this module's own "reuse what's already a dependency" approach to
    /// `new_id`. Not cleaned up afterward (OS temp dir, negligible size,
    /// matches this codebase having no existing temp-dir test precedent to
    /// follow either way).
    struct TempDir(PathBuf);

    impl TempDir {
        fn new() -> Self {
            let mut suffix = [0u8; 8];
            rand::thread_rng().fill_bytes(&mut suffix);
            let dir = std::env::temp_dir().join(format!(
                "rose-theme-test-{}",
                data_encoding::HEXLOWER.encode(&suffix)
            ));
            fs::create_dir_all(&dir).unwrap();
            TempDir(dir)
        }

        fn path(&self) -> &Path {
            &self.0
        }
    }

    #[test]
    fn list_always_includes_every_built_in_first_and_only_them() {
        let dir = TempDir::new();
        let themes = list(dir.path()).unwrap();
        assert_eq!(themes.len(), BUILT_IN_THEME_IDS.len());
        for (theme, expected_id) in themes.iter().zip(BUILT_IN_THEME_IDS.iter()) {
            assert_eq!(&theme.id, expected_id);
            assert!(theme.built_in);
        }
    }

    #[test]
    fn upsert_with_no_id_creates_and_generates_an_id_not_colliding_with_a_built_in() {
        let dir = TempDir::new();
        let theme = upsert(
            dir.path(),
            ThemeInput {
                id: None,
                name: "My Theme".to_string(),
                colors: sample_colors(),
            },
        )
        .unwrap();

        assert!(!is_built_in_id(&theme.id));
        assert!(!theme.built_in);
        assert_eq!(list(dir.path()).unwrap().len(), BUILT_IN_THEME_IDS.len() + 1);
    }

    #[test]
    fn upsert_with_existing_id_updates_in_place() {
        let dir = TempDir::new();
        let created = upsert(
            dir.path(),
            ThemeInput {
                id: None,
                name: "Original".to_string(),
                colors: sample_colors(),
            },
        )
        .unwrap();

        let updated = upsert(
            dir.path(),
            ThemeInput {
                id: Some(created.id.clone()),
                name: "Renamed".to_string(),
                colors: sample_colors(),
            },
        )
        .unwrap();

        assert_eq!(updated.id, created.id);
        let all = list(dir.path()).unwrap();
        assert_eq!(all.len(), BUILT_IN_THEME_IDS.len() + 1);
        assert_eq!(all.last().unwrap().name, "Renamed");
    }

    #[test]
    fn upsert_rejects_every_built_in_id() {
        let dir = TempDir::new();
        for id in BUILT_IN_THEME_IDS {
            let result = upsert(
                dir.path(),
                ThemeInput {
                    id: Some(id.to_string()),
                    name: "Hijacked".to_string(),
                    colors: sample_colors(),
                },
            );
            assert!(result.is_err(), "expected upsert({id}) to be rejected");
        }
    }

    #[test]
    fn delete_removes_a_saved_theme() {
        let dir = TempDir::new();
        let created = upsert(
            dir.path(),
            ThemeInput {
                id: None,
                name: "Temp".to_string(),
                colors: sample_colors(),
            },
        )
        .unwrap();

        delete(dir.path(), &created.id).unwrap();
        assert_eq!(list(dir.path()).unwrap().len(), BUILT_IN_THEME_IDS.len());
    }

    #[test]
    fn delete_errors_on_unknown_id() {
        let dir = TempDir::new();
        let result = delete(dir.path(), "does-not-exist");
        assert!(matches!(result, Err(AppError::ThemeNotFound)));
    }

    #[test]
    fn delete_rejects_every_built_in_id() {
        let dir = TempDir::new();
        for id in BUILT_IN_THEME_IDS {
            let result = delete(dir.path(), id);
            assert!(result.is_err(), "expected delete({id}) to be rejected");
        }
    }

    #[test]
    fn get_returns_every_built_in_without_touching_disk() {
        let dir = TempDir::new();
        for id in BUILT_IN_THEME_IDS {
            assert!(get(dir.path(), id).unwrap().built_in, "expected get({id}) to be built-in");
        }
    }
}
